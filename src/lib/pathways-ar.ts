// Arabic wording for pathway options (patient-facing). Prototype translation in
// Modern Standard Arabic; requires review by a native-speaking clinician.

import type { PathwayContext } from "@/lib/pathways";

export interface OptionAr {
  title: string;
  text: string;
  reason: string;
}

const n = (x: number | null | undefined) => (x === null || x === undefined ? "–" : x.toLocaleString("ar-EG"));

export function optionArabic(ruleId: string, c: PathwayContext): OptionAr | null {
  const months = n(c.monthsTrying);
  const age = n(c.age);
  const bmi = c.bmi !== null ? c.bmi.toFixed(1) : "–";
  switch (ruleId) {
    case "RF-CYCLE":
      return {
        title: c.cycleRegularity === "AMENORRHEA" ? "انقطاع الدورة يحتاج إلى فحص" : "عدم انتظام الدورة يستحق الفحص",
        text: "قد يكون لعدم انتظام الدورة أو انقطاعها أسباب قابلة للعلاج مثل اضطرابات الغدة الدرقية أو الهرمونات. من الأفضل مراجعة الطبيب بدل الانتظار.",
        reason: "نمط الدورة كما ذكرتِ في استبيانك."
      };
    case "RF-HISTORY":
      return {
        title: "تاريخك الصحي يعني أن النصيحة المبكرة قد تفيدك",
        text: "قد تؤثر بعض الحالات أو العلاجات السابقة في الخصوبة. يستطيع الأخصائي تقديم المشورة مبكرًا حتى لو لم تكن تخطط للحمل الآن.",
        reason: "تاريخ صحي ذكرته في استبيانك."
      };
    case "REF-12M":
      return {
        title: "راجع أخصائي خصوبة",
        text: "بعد سنة من المحاولة دون حمل، يُنصح بتقييم الخصوبة للزوجين معًا. هذا أمر شائع، وكثير من الأسباب قابلة للعلاج.",
        reason: `المحاولة منذ ${months} شهرًا.`
      };
    case "REF-6M-35":
      return {
        title: "راجع أخصائي خصوبة الآن بدل الانتظار",
        text: "بعد سن ٣٥ ينصح الأطباء بالتقييم بعد ستة أشهر من المحاولة، لأن الوقت يؤثر أكثر في خيارات العلاج.",
        reason: `العمر ${age}، والمحاولة منذ ${months} شهرًا.`
      };
    case "REF-40":
      return {
        title: "رتّب مراجعة الأخصائي قريبًا",
        text: "من سن الأربعين يُنصح بمراجعة الأخصائي مبكرًا عند محاولة الحمل.",
        reason: `العمر ${age}.`
      };
    case "RES-LOW":
      return {
        title: "ناقشي نتيجة مخزون المبيض مع أخصائي",
        text: "نتيجتك أقل من النطاق المستخدم لتعريف المخزون المعتاد للبويضات. هذا لا يعني عدم القدرة على الحمل، لكنه قد يعني وقتًا أقل للتخطيط، لذا فالحديث مع الأخصائي مفيد.",
        reason: "آخر نتيجة لـ AMH أو عدد الجريبات أقل من الحد المرجعي."
      };
    case "TEST-AMH":
      return {
        title: "فكّري في فحص مخزون المبيض (AMH)",
        text: "يعطي تحليل الدم AMH، مع الأشعة أحيانًا، صورة عن مخزون البويضات مقارنةً بعمرك. يساعدك على التخطيط، لكنه لا يتنبأ بقدرتك على الحمل الطبيعي.",
        reason: c.familyEarlyMenopause ? "تاريخ عائلي لانقطاع الطمث المبكر." : `العمر ${age} ولا توجد نتيجة لمخزون المبيض مسجّلة.`
      };
    case "PRES-DISCUSS":
      return {
        title: "ناقشي تجميد البويضات إن كان يهمّك",
        text: "تكون نتائج تجميد البويضات أفضل في الأعمار الأصغر. إن كنتِ من حاملات بطاقة «ثقة»، فهي تغطي تجميد البويضات الاختياري للعضوات غير المتزوجات المؤهلات: حتى دورتين مدى الحياة، وتخزين لمدة خمس سنوات، مع تقييم نفسي قبل البدء. تختلف خطط التأمين الأخرى. يستطيع الأخصائي إخبارك إن كان مناسبًا لك.",
        reason: c.preservationIntent ? "ذكرتِ أنك تفكرين في ذلك." : "مخزون البويضات في الجزء الأدنى من النطاق أو أقل منه."
      };
    case "SEM-LOW":
      return {
        title: "أعد تحليل السائل المنوي وراجع أخصائيًا",
        text: "نتيجة واحدة أو أكثر أقل من النطاق المرجعي. تختلف النتائج من تحليل لآخر، لذا فإعادة التحليل هي الخطوة الأولى، ويمكن لأخصائي الذكورة أو المسالك البولية اكتشاف أسباب قابلة للعلاج.",
        reason: "آخر تحليل للسائل المنوي فيه قيم أقل من الحدود المرجعية."
      };
    case "TEST-SEMEN":
      return {
        title: "فكّر في تحليل السائل المنوي",
        text: "تحليل السائل المنوي فحص بسيط وخاص. العوامل الذكورية تشارك في نحو نصف حالات تأخر الحمل، وغالبًا ما تُكتشف متأخرة.",
        reason: "لا يوجد تحليل للسائل المنوي مسجّل."
      };
    case "BBT-MONO":
      return {
        title: "اسألي طبيبك عن نمط حرارة جسمك",
        text: "لم تُظهر قراءات الحرارة الارتفاع المعتاد بعد الإباضة حتى الآن. هذا يختلف من دورة لأخرى وليس تشخيصًا، لكنه يستحق المراجعة مع طبيبك.",
        reason: "لا يوجد ارتفاع مستمر في قراءاتك الأخيرة."
      };
    case "PRECON":
      return {
        title: "فحص ما قبل الحمل",
        text: "تشمل زيارة ما قبل الحمل حمض الفوليك والتطعيمات والأدوية وأي حالات مزمنة، للزوجين.",
        reason: c.tryingToConceive ? "أنتما تحاولان الحمل." : "أنت مرتبط بشريك."
      };
    case "BMI-35-40":
      return {
        title: "دعم الوزن قبل أي علاج للخصوبة",
        text: "قبل علاج الخصوبة يُنصح ببرنامج تغذية لمدة ثلاثة أشهر على الأقل عند هذا الوزن، لأنه يحسّن فرص نجاح العلاج.",
        reason: `مؤشر كتلة الجسم ${bmi}.`
      };
    case "BMI-OUT":
      return {
        title: "تحدّث مع طبيب عن الوزن والخصوبة",
        text: "مؤشر كتلة الجسم لديك خارج النطاق المطلوب عادةً قبل علاج الخصوبة. يستطيع الطبيب أو أخصائي التغذية مساعدتك في التخطيط.",
        reason: `مؤشر كتلة الجسم ${bmi}.`
      };
    case "OPT-SMOKING":
      return {
        title: "الإقلاع عن التدخين يحسّن الخصوبة",
        text: "يقلّل التدخين الخصوبة لدى النساء والرجال. يتوفر دعم مجاني للإقلاع عن التدخين عبر الرعاية الأولية.",
        reason: "ذكرت أنك تدخّن."
      };
    case "OPT-WEIGHT":
      return {
        title: "الوزن الصحي يدعم الخصوبة",
        text: "الاقتراب من مؤشر كتلة جسم بين ٢٠ و٢٥ يدعم انتظام الإباضة وصحة الحيوانات المنوية. التغييرات الصغيرة المستمرة مهمة.",
        reason: `مؤشر كتلة الجسم ${bmi}.`
      };
    case "OPT-SLEEP":
      return {
        title: "احرص على النوم سبع ساعات أو أكثر",
        text: "النوم المنتظم والكافي يدعم الهرمونات المرتبطة بالخصوبة.",
        reason: c.meanSleepHours !== null ? `متوسط نومك ${c.meanSleepHours.toFixed(1)} ساعات.` : ""
      };
    case "OPT-GENERAL":
      return {
        title: "استمر في بناء صورتك الصحية",
        text: "لا يوجد ما يتطلب إجراءً الآن. تحديث معلوماتك يساعدك ويساعد طبيبك على ملاحظة التغيّرات مبكرًا.",
        reason: "لم تنطبق أي قاعدة على معلوماتك الحالية."
      };
    default:
      return null;
  }
}
