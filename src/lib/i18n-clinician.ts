/** Arabic number + noun agreement: 1 شهر, 2 شهران, 3–10 أشهر, 11+ شهرًا. */
function countAr(n: number, one: string, two: string, few: string, many: string): string {
  const k = Math.abs(n) % 100;
  if (n === 1) return one;
  if (n === 2) return two;
  if (k >= 3 && k <= 10) return `${n} ${few}`;
  return `${n} ${many}`;
}
