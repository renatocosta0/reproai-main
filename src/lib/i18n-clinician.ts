export const CLINICIAN_STRINGS: Record<Locale, ClinicianStrings> = { en, ar };

const DATE_LOCALE: Record<Locale, string> = { en: "en-GB", ar: "ar-AE-u-nu-latn" };

/** Same output as shortDate() in English; Arabic month names with Western digits otherwise. */
export function shortDateL(locale: Locale, d: Date | string): string {
  const date = new Date(d);
  const sameYear = date.getFullYear() === new Date().getFullYear();
  return date.toLocaleDateString(DATE_LOCALE[locale], { day: "numeric", month: "short", ...(sameYear ? {} : { year: "numeric" }) });
}

export function longDateL(locale: Locale, d: Date | string, opts: Intl.DateTimeFormatOptions): string {
  return new Date(d).toLocaleDateString(DATE_LOCALE[locale], opts);
}

/** timeAgo() from src/lib/format.ts in Arabic (Intl handles Arabic plural forms). */
export function timeAgoAr(iso: string | Date): string {
  const rtf = new Intl.RelativeTimeFormat("ar-AE-u-nu-latn", { numeric: "auto" });
  const ms = Date.now() - new Date(iso).getTime();
  const min = Math.round(ms / 60000);
  if (min < 1) return "الآن";
  if (min < 60) return rtf.format(-min, "minute");
  const h = Math.round(min / 60);
  if (h < 24) return rtf.format(-h, "hour");
  const d = Math.round(h / 24);
  if (d < 30) return rtf.format(-d, "day");
  return shortDateL("ar", iso);
}
