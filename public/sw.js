// Service Worker for ReproAI Push Notifications.
// Displays privacy-compliant notifications on mobile lock screen & desktop even when app is closed.

self.addEventListener("install", (event) => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim());
});

self.addEventListener("push", (event) => {
  let data = {
    title: "ReproAI · Care Update",
    body: "Your healthcare provider updated your personalized care guidance. Tap to view.",
    url: "/patient/assessment"
  };

  if (event.data) {
    try {
      data = { ...data, ...event.data.json() };
    } catch {
      data.body = event.data.text() || data.body;
    }
  }

  const options = {
    body: data.body,
    icon: "/logo.svg",
    badge: "/logo.svg",
    tag: "reproai-care-update",
    renotify: true,
    requireInteraction: true,
    data: {
      url: data.url || "/patient/assessment"
    }
  };

  event.waitUntil(self.registration.showNotification(data.title, options));
});

self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  const urlToOpen = event.notification.data?.url || "/patient/assessment";

  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((windowClients) => {
      for (const client of windowClients) {
        if (client.url.includes("/patient") && "focus" in client) {
          client.navigate(urlToOpen);
          return client.focus();
        }
      }
      if (self.clients.openWindow) {
        return self.clients.openWindow(urlToOpen);
      }
    })
  );
});
